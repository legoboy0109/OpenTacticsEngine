# Compiles the Direct3D 11 backend's shaders (engine\gfx3d\d3d11\shaders\render3d.hlsl) into C headers of bytecode
# next to it, with fxc.exe from the Windows SDK. Run after changing the HLSL and commit the headers with it: the engine
# itself never needs fxc (docs/RENDER3D.md "Direct3D 11 backend").
#
#   powershell -ExecutionPolicy Bypass -File tools\windows\make_d3d11_shaders.ps1 [-Fxc C:\path\to\fxc.exe]
#
# Shader Model 4.0 (vs_4_0 / ps_4_0): runs on feature level 10_0 and up, which covers Xbox One (10_1).
param([string]$Fxc = '')
$ErrorActionPreference = 'Stop'

$repo = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$dir = Join-Path $repo 'engine\gfx3d\d3d11\shaders'
$hlsl = Join-Path $dir 'render3d.hlsl'

if (-not $Fxc) {
  # The newest Windows 10/11 SDK that has an x64 fxc.
  $kits = Join-Path ${env:ProgramFiles(x86)} 'Windows Kits\10\bin'
  $found = Get-ChildItem $kits -Directory -ErrorAction SilentlyContinue | Where-Object { Test-Path (Join-Path $_.FullName 'x64\fxc.exe') } |
    Sort-Object { [version]($_.Name) } -ErrorAction SilentlyContinue | Select-Object -Last 1
  if (-not $found) { throw "fxc.exe not found under $kits; install the Windows SDK or pass -Fxc" }
  $Fxc = Join-Path $found.FullName 'x64\fxc.exe'
}
Write-Host "fxc: $Fxc"

# entry point, profile, header file, array name
$jobs = @(
  @('vsMain', 'vs_4_0', 'render3d_vs.h', 'kRender3dVs'),
  @('psMain', 'ps_4_0', 'render3d_ps.h', 'kRender3dPs'),
  @('quadVsMain', 'vs_4_0', 'quad_vs.h', 'kQuadVs'),
  @('quadPsMain', 'ps_4_0', 'quad_ps.h', 'kQuadPs')
)
foreach ($j in $jobs) {
  $out = Join-Path $dir $j[2]
  $tmp = "$out.tmp"
  & $Fxc /nologo /O3 /WX /Qstrip_reflect /Qstrip_debug /E $j[0] /T $j[1] /Vn $j[3] /Fh $tmp $hlsl
  if ($LASTEXITCODE -ne 0) { throw "fxc failed on $($j[0])" }
  # fxc writes "const BYTE name[]" (a windows.h type) with CRLF line ends: make it plain C++ with LF, and say where it
  # came from.
  $text = [IO.File]::ReadAllText($tmp)
  $text = $text -replace "`r`n", "`n"
  $text = $text -replace 'const BYTE ', 'static const unsigned char '
  $head = "// Generated by tools/windows/make_d3d11_shaders.ps1 from render3d.hlsl ($($j[0]), $($j[1])). Do not edit.`n"
  [IO.File]::WriteAllText($out, $head + $text, (New-Object Text.UTF8Encoding $false))
  Remove-Item $tmp
  Write-Host "wrote $out"
}
