namespace {

void setBaseState() {
  uint32_t* p = begin();
  // Rectangles the chip may draw in: all eight are the whole screen until a 3D picture narrows them.
  p = pb_push1(p, NV097_SET_WINDOW_CLIP_TYPE, 0);
  for (int i = 0; i < 8; ++i) {
    p = pb_push1(p, NV097_SET_WINDOW_CLIP_HORIZONTAL + 4 * i, 0 | ((g_width - 1) << 16));
    p = pb_push1(p, NV097_SET_WINDOW_CLIP_VERTICAL + 4 * i, 0 | ((g_height - 1) << 16));
  }
  // pbkit's surface setup (pb_target_back_buffer) turns on "Z_PERSPECTIVE_ENABLE", which makes the depth buffer a W-buffer. Our
  // vertex program already divided z by w, so depth must be plain z: stencil write on, texture perspective on, z perspective off.
  p = pb_push1(p, NV097_SET_CONTROL0, NV097_SET_CONTROL0_STENCIL_WRITE_ENABLE | NV097_SET_CONTROL0_TEXTURE_PERSPECTIVE_ENABLE);
  p = pb_push1(p, NV097_SET_COLOR_MASK, 0x01010101);
  p = pb_push1(p, NV097_SET_BLEND_EQUATION, NV097_SET_BLEND_EQUATION_V_FUNC_ADD);
  p = pb_push1(p, NV097_SET_FRONT_FACE, NV097_SET_FRONT_FACE_V_CCW);  // (the chip judges the order after our own viewport flip of y)
  p = pb_push1(p, NV097_SET_CULL_FACE, NV097_SET_CULL_FACE_V_BACK);
  p = pb_push1(p, NV097_SET_FOG_ENABLE, 0);  // the fog is done in the combiner (hw3d_ps.rc)
  p = pb_push1(p, NV097_SET_LIGHTING_ENABLE, 0);
  p = pb_push1(p, NV097_SET_STENCIL_TEST_ENABLE, 0);
  p = pb_push1(p, NV097_SET_TRANSFORM_EXECUTION_MODE,
               OTE_MASK(NV097_SET_TRANSFORM_EXECUTION_MODE_MODE, NV097_SET_TRANSFORM_EXECUTION_MODE_MODE_PROGRAM) |
                   OTE_MASK(NV097_SET_TRANSFORM_EXECUTION_MODE_RANGE_MODE, NV097_SET_TRANSFORM_EXECUTION_MODE_RANGE_MODE_PRIV));
  end(p);
}

}  // namespace

void beginFrame() {
  if (!g_started || g_frameOpen) return;
  // First the chip must be done with the previous frame: its commands are in the push buffer we are about to write over,
  // its vertices and textures may change now. (The wait for the vertical blank comes at the end of endFrame.)
  {
    prof::Span wait(prof::kChipWait);
    while (pb_busy()) {
    }
    g_idleSeq = g_useSeq;
  }
  // The buffer this frame draws into must not be the one on the screen: pbkit's three buffers rotate on their own, and a frame
  // queued behind another one comes round to the buffer being shown (it would be drawn while it is scanned out: torn, flickering
  // pictures). Wait for the vertical blank that moves the display on (docs/XBOX_OG.md "Pacing").
  if (shownBuffer() == targetBuffer()) {
    ++g_onScreenBegin;
    if (flipGuard()) {
      prof::Span wait(prof::kVblank);
      while (shownBuffer() == targetBuffer()) pb_wait_for_vbl();
    }
  }
  pb_reset();
  pb_target_back_buffer();
  g_frameBase = pb_begin();
  g_dropped = 0;
  g_scratchUsed = 0;
  g_arrays = -1;
  g_frameOpen = true;
  setBaseState();
}

bool inFrame() { return g_frameOpen; }

void waitIdle() {
  if (!g_started) return;
  kick();
  prof::Span wait(prof::kChipWait);
  while (pb_busy()) {
  }
  g_idleSeq = g_useSeq;
}

uint32_t noteUse() { return ++g_useSeq; }
uint32_t idleSeq() { return g_idleSeq; }

void endFrame() {
  if (!g_started || !g_frameOpen) return;
  kick();
  const uint32_t drawnBuffer = targetBuffer();
  g_lastPush = (size_t)(pb_begin() - g_frameBase) * 4;
  // pbkit has three frame buffers and flips to a finished one at the next vertical blank by itself. pb_finished() queues this
  // frame for that flip and answers 1 when two frames are already waiting: that is the only time the player has to wait (for a
  // blank, which frees a buffer). A frame that takes slightly longer than 16.7 ms then costs one repeated picture, not a whole
  // 33 ms interval as it did when every frame ended with a wait for the next blank. OTE_XBOX_PACE=vbl brings that wait back
  // (for comparing: docs/XBOX_OG.md "Speed").
  {
    prof::Span vbl(prof::kVblank);
    while (pb_finished()) pb_wait_for_vbl();
    static int everyBlank = -1;
    if (everyBlank < 0) {
      const char* e = getenv("OTE_XBOX_PACE");
      everyBlank = e && strcmp(e, "vbl") == 0;
    }
    if (everyBlank) pb_wait_for_vbl();
  }
  g_frameOpen = false;
  {  // diagnostics: was the frame drawn into a buffer that is on the screen now, and how many blanks passed since the last frame
    if (shownBuffer() == drawnBuffer) ++g_onScreenEnd;
    if (pb_busy()) ++g_busyAtBlank;  // the chip was still drawing when the blank came (a picture shown half done, if it was this one)
    const uint32_t v = pb_get_vbl_counter();
    ++g_vblDelta[v - g_lastVbl > 3 ? 3 : v - g_lastVbl];
    g_lastVbl = v;
    ++g_framesCounted;
  }
  if (g_dropped) {
    g_droppedTotal += g_dropped;
    OTE_WARN("3D drawing: %d draws dropped this frame, the push buffer was full (%d so far)", g_dropped, g_droppedTotal);
  }
}

void noteHazard() { ++g_hazards; }

void flipStats(char* out, int size) {
  snprintf(out, (size_t)size, "frames %d, chip still busy at the blank %d, drawn into the shown buffer: at start %d, at end %d; blanks since last frame 0:%d 1:%d 2:%d 3+:%d; meshes rewritten while the chip may read them %d",
           g_framesCounted, g_busyAtBlank, g_onScreenBegin, g_onScreenEnd, g_vblDelta[0], g_vblDelta[1], g_vblDelta[2], g_vblDelta[3], g_hazards);
  g_framesCounted = g_hazards = g_busyAtBlank = g_onScreenBegin = g_onScreenEnd = 0;
  g_vblDelta[0] = g_vblDelta[1] = g_vblDelta[2] = g_vblDelta[3] = 0;
}

const uint8_t* backBuffer(int& w, int& h, int& pitch) {
  if (!g_started) return nullptr;
  w = g_width;
  h = g_height;
  pitch = (int)pb_back_buffer_pitch();
  return (const uint8_t*)pb_back_buffer();
}

