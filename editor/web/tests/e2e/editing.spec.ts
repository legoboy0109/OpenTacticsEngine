test('@smoke edit a unit name and a stat: saved, survives reload, is on disk', async ({ page, game }) => {
  const id = await game.create('strategy-rpg', 'Persist')
  await page.goto(editorUrl(id, 'units', 'lord'))
  await page.getByLabel('Name', { exact: true }).fill('Sir Lord')
  await page.getByLabel('Strength Value').fill('9')
  await expect(page.getByText('Unsaved changes')).toBeVisible()
  await saved(page)
  await page.reload()
  await expect(page.getByLabel('Name', { exact: true })).toHaveValue('Sir Lord')
  await expect(page.getByLabel('Strength Value')).toHaveValue('9')
  const lord = readDisk(id, 'data/units.json').units.find((u: any) => u.id === 'lord')
  expect(lord.name).toBe('Sir Lord')
  expect(lord.stats.str).toBe(9)
  expect(typeof lord.stats.str).toBe('number')
  expect(lord.id).toBe('lord')
})

test('@smoke undo and redo with buttons and keyboard', async ({ page, game }) => {
  const id = await game.create('strategy-rpg', 'Undo')
  await page.goto(editorUrl(id, 'units', 'lord'))
  const name = page.getByLabel('Name', { exact: true })
  await expect(page.getByRole('button', { name: 'Undo' })).toBeDisabled()
  await name.fill('Zed')
  await name.pressSequentially('ig')
  await page.getByRole('button', { name: 'Undo' }).click()
  await expect(name).toHaveValue('Lord') // typing was one undo step
  await page.getByRole('button', { name: 'Redo' }).click()
  await expect(name).toHaveValue('Zedig')
  await page.keyboard.press('Control+z')
  await expect(name).toHaveValue('Lord')
  await page.keyboard.press('Control+Shift+z')
  await expect(name).toHaveValue('Zedig')
  await saved(page)
  expect(readDisk(id, 'data/units.json').units[0].name).toBe('Zedig')
  await page.keyboard.press('Control+z')
  await saved(page)
  expect(readDisk(id, 'data/units.json').units[0].name).toBe('Lord')
})

test('@smoke a weapon used by a unit: deleting asks, lists the unit, cleans up', async ({ page, game }) => {
  const id = await game.create('strategy-rpg', 'Weapons')
  await page.goto(editorUrl(id, 'weapons'))
  await page.getByRole('button', { name: 'New weapon' }).click()
  await page.getByLabel('Name of the weapon').fill('Plasma Rod')
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/weapons\/plasma_rod/)
  await section(page, 'Units').click()
  await page.getByRole('button', { name: /^Lord/ }).click()
  await page.getByLabel('Plasma Rod').check()
  await saved(page)
  expect(readDisk(id, 'data/units.json').units[0].weapons).toContain('plasma_rod')

  await section(page, 'Weapons').click()
  await page.getByRole('button', { name: /^Plasma Rod/ }).click()
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('Lord')
  await dialog.getByRole('button', { name: 'Delete' }).click()
  await saved(page)
  expect(readDisk(id, 'data/units.json').units[0].weapons).not.toContain('plasma_rod')
  expect(readDisk(id, 'data/weapons.json').weapons.some((w: any) => w.id === 'plasma_rod')).toBe(false)
  await expect(page.getByRole('button', { name: 'No problems' })).toBeVisible()
  // One undo brings the weapon and its use back.
  await page.getByRole('button', { name: 'Undo' }).click()
  await saved(page)
  expect(readDisk(id, 'data/units.json').units[0].weapons).toContain('plasma_rod')
})

test('terrain colour, movement cost and impassable edits persist', async ({ page, game }) => {
  const id = await game.create('strategy-rpg', 'Terrain')
  await page.goto(editorUrl(id, 'terrain', 'forest'))
  await page.getByLabel('Forest colour (hex code)').fill('#112233')
  await page.getByLabel('Foot cost').fill('3')
  await page.getByLabel('Horse cannot enter').check()
  await saved(page)
  await page.reload()
  await expect(page.getByLabel('Forest colour (hex code)')).toHaveValue('#112233')
  await expect(page.getByLabel('Horse cost')).toBeDisabled()
  const f = readDisk(id, 'data/terrain.json').terrain.find((t: any) => t.id === 'forest')
  expect(f.color).toBe('#112233')
  expect(f.moveCost).toEqual({ foot: 3, horse: 0 })
  await page.getByLabel('Horse cannot enter').uncheck()
  await saved(page)
  expect(readDisk(id, 'data/terrain.json').terrain.find((t: any) => t.id === 'forest').moveCost).toEqual({ foot: 3 })
})

test('keyboard only: create a unit', async ({ page, game }) => {
  const id = await game.create('strategy-rpg', 'Keys')
  await page.goto(editorUrl(id, 'units'))
  await page.getByRole('button', { name: 'New unit' }).focus()
  await page.keyboard.press('Enter')
  await page.keyboard.type('Dragoon')
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/units\/dragoon/)
  await expect(page.getByRole('heading', { name: 'Dragoon' })).toBeVisible()
  await saved(page)
  const u = readDisk(id, 'data/units.json').units.find((x: any) => x.id === 'dragoon')
  expect(u).toMatchObject({ name: 'Dragoon', glyph: 'D', moveType: 'foot' })
  expect(readFileSync(diskPath(id, 'data/units.json'), 'utf8')).toContain('Dragoon')
  await expect(page.getByRole('button', { name: 'No problems' })).toBeVisible()
})
