for (const template of ['strategy-rpg', 'economy-tactics', 'blank']) {
  test(`@smoke new game from the ${template} template opens with zero problems`, async ({ page, request }) => {
    const name = `Fresh ${template} ${Date.now().toString(36)}`
    await page.goto('/')
    await page.getByRole('button', { name: 'New game' }).click()
    await page.getByLabel('Name of your game').fill(name)
    await page.getByRole('radiogroup').locator('label', { hasText: new RegExp(`^${template === 'blank' ? 'Blank' : template === 'economy-tactics' ? 'Economy Tactics' : 'Strategy RPG'}`) }).click()
    await page.getByRole('button', { name: 'Create game' }).click()
    await expect(page).toHaveURL(/\/p\/[a-z0-9-]+\/game/)
    await expect(page.getByLabel('Name', { exact: true })).toHaveValue(name)
    await expect(page.getByRole('button', { name: 'No problems' })).toBeVisible()
    const id = new URL(page.url()).pathname.split('/')[2]
    expect((await (await request.get(`/api/projects/${id}/problems`)).json()).problems).toEqual([])
  })
}

