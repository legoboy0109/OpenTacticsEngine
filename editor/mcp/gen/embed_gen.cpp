// Build-time helper: turns files into a C++ source with byte arrays, so ote-mcp carries the schemas and docs inside the
// program without Qt resources or a runtime data folder. Arrays of numbers (not string literals) keep MSVC's literal size
// limit out of the picture.
//   embed_gen OUT.cpp --group NAME [--strip-ext] FILE... [--group NAME2 FILE...]
// Produces, per group: `const ote_mcp::Embedded kNAME[]` and `const size_t kNAMECount`, entries named by file name
// (without the extension when --strip-ext is given).
#include <cstdio>
#include <fstream>
#include <iterator>
#include <string>
#include <vector>

struct Group {
  std::string name;
  bool stripExt = false;
  std::vector<std::string> files;
};

int main(int argc, char** argv) {
  if (argc < 3) { std::fprintf(stderr, "usage: embed_gen OUT.cpp --group NAME [--strip-ext] FILE...\n"); return 2; }
  std::vector<Group> groups;
  for (int i = 2; i < argc; ++i) {
    const std::string a = argv[i];
    if (a == "--group" && i + 1 < argc) { groups.emplace_back(); groups.back().name = argv[++i]; }
    else if (a == "--strip-ext" && !groups.empty()) groups.back().stripExt = true;
    else if (!groups.empty()) groups.back().files.push_back(a);
  }
  std::string out = "// Generated by embed_gen at build time. Do not edit.\n#include \"embedded.h\"\nnamespace ote_mcp {\nnamespace {\n";
  std::vector<size_t> sizes;
  int n = 0;
  for (const Group& g : groups) {
    for (const std::string& path : g.files) {
      std::ifstream f(path, std::ios::binary);
      if (!f) { std::fprintf(stderr, "embed_gen: cannot read %s\n", path.c_str()); return 1; }
      std::string bytes((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
      sizes.push_back(bytes.size());
      out += "const unsigned char d" + std::to_string(n++) + "[] = {";
      char buf[8];
      for (size_t i = 0; i < bytes.size(); ++i) {
        if (i % 24 == 0) out += "\n";
        std::snprintf(buf, sizeof buf, "%u,", (unsigned)(unsigned char)bytes[i]);
        out += buf;
      }
      out += "0};\n";  // a trailing 0 so the array is never empty
    }
  }
  out += "}  // namespace\n";
  n = 0;
  for (const Group& g : groups) {
    out += "const Embedded k" + g.name + "[] = {\n";
    for (const std::string& path : g.files) {
      const size_t slash = path.find_last_of("/\\");
      std::string name = slash == std::string::npos ? path : path.substr(slash + 1);
      if (g.stripExt) name = name.substr(0, name.find_last_of('.'));
      out += "  {\"" + name + "\", d" + std::to_string(n) + ", " + std::to_string(sizes[(size_t)n]) + "},\n";
      ++n;
    }
    out += "};\nconst size_t k" + g.name + "Count = " + std::to_string(g.files.size()) + ";\n";
  }
  out += "}  // namespace ote_mcp\n";
  std::ofstream o(argv[1], std::ios::binary);
  o << out;
  return o ? 0 : 1;
}
